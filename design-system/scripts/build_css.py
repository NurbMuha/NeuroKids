#!/usr/bin/env python3
"""Export design-system/tokens.json -> design-system/tokens.css.

CSS custom property names come from each token's codeSyntax.WEB
(var(--nk-...)), so code and Figma share one naming source.
Semantic tokens stay references to primitives (var(--nk-blue-500)).
Typography styles become both custom properties and utility classes:
  --nk-type-display-xl: 800 64px/1 var(--nk-font-body);
  --nk-type-display-xl-tracking: -0.03em;
  .nk-display-xl { font: ...; letter-spacing: ... }

Run:  python3 -I design-system/scripts/build_css.py
Never hand-edit tokens.css; regenerate it.
"""
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "tokens.json"
OUT = ROOT / "tokens.css"

FONT_STACK = '"{family}", system-ui, -apple-system, "Segoe UI", Roboto, sans-serif'


def web_name(node):
    code = node.get("$extensions", {}).get("com.figma", {}).get("codeSyntax", {}).get("WEB", "")
    m = re.match(r"var\((--[a-z0-9-]+)\)", code)
    return m.group(1) if m else None


def walk(node, path=()):
    if isinstance(node, dict):
        if "$value" in node:
            yield path, node
            return
        for k, v in node.items():
            if not k.startswith("$"):
                yield from walk(v, path + (k,))


def main():
    tokens = json.loads(SRC.read_text(encoding="utf-8"))

    # index every token by its dotted reference path -> css var name
    ref_to_var = {}
    for path, node in walk(tokens):
        name = web_name(node)
        if name:
            ref_to_var[".".join(path)] = name

    def resolve(value):
        if isinstance(value, str):
            m = re.fullmatch(r"\{([^}]+)\}", value)
            if m:
                key = m.group(1)
                if key not in ref_to_var:
                    raise KeyError(f"unresolved reference {value}")
                return f"var({ref_to_var[key]})"
        return value

    lines = ["/* Generated by design-system/scripts/build_css.py from tokens.json. Do not edit. */",
             ":root {"]

    groups = [("primitives", "Primitives"), ("color", "Color / Light"), ("spacing", "Spacing"),
              ("radius", "Radius"), ("size", "Size"), ("motion", "Motion")]
    for key, title in groups:
        lines.append(f"  /* {title} */")
        for path, node in walk(tokens[key], (key,)):
            name = web_name(node)
            if not name:
                continue
            value = node["$value"]
            if node.get("$type") == "cubicBezier":
                value = "cubic-bezier({})".format(", ".join(str(v) for v in value))
            else:
                value = resolve(value)
            lines.append(f"  {name}: {value};")

    # font family (same family in every language mode today)
    font = tokens["font"]["body"]["$value"]
    family = font["EN"] if isinstance(font, dict) else font
    lines.append("  /* Typography */")
    lines.append(f"  --nk-font-body: {FONT_STACK.format(family=family)};")

    classes = []
    for path, node in walk(tokens["typography"]):
        style = "/".join(path)  # e.g. Display/XL
        v = node["$value"]
        slug = re.sub(r"[^a-z0-9]+", "-", style.lower()).strip("-")
        tracking = float(str(v.get("letterSpacing", "0")).rstrip("%")) / 100
        lh = v["lineHeight"]
        font_short = f"{v['fontWeight']} {v['fontSize']}/{lh} var(--nk-font-body)"
        lines.append(f"  --nk-type-{slug}: {font_short};")
        lines.append(f"  --nk-type-{slug}-tracking: {tracking:g}em;")
        extra = "  text-transform: uppercase;\n" if style == "Label/Overline" else ""
        classes.append(
            f".nk-{slug} {{\n  font: var(--nk-type-{slug});\n"
            f"  letter-spacing: var(--nk-type-{slug}-tracking);\n{extra}}}"
        )
    lines.append("}")
    lines.append("")
    lines.append("/* Text styles (Figma: Typography/*) */")
    lines.extend(classes)
    lines.append("")

    OUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT.parent)}: {len(ref_to_var)} tokens, {len(classes)} text styles")


if __name__ == "__main__":
    main()
